"""Regenerate Shadowrocket rules from Ho-New and MetaCubeX's text exports."""

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import ipaddress
import json
from pathlib import Path
import re
import subprocess
from urllib.request import urlopen

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "shadowrocket"
CONFIG = ROOT / "Shadowrocket-Ho-New.conf"
UPSTREAM = "https://github.com/MetaCubeX/meta-rules-dat.git"
RAW = "https://raw.githubusercontent.com/MetaCubeX/meta-rules-dat"
PUBLISHED = "https://raw.githubusercontent.com/Hotinosin/mihomo_template/main/shadowrocket"


def convert(kind, content):
    result = []
    for raw in content.splitlines():
        value = raw.strip()
        if not value or value.startswith("#"):
            continue
        if kind == "geosite":
            suffix = value.startswith("+.")
            domain = value[2:] if suffix else value
            if not re.fullmatch(r"[A-Za-z0-9_\-]+(?:\.[A-Za-z0-9_\-]+)*", domain):
                raise ValueError(f"Unsupported domain entry: {value!r}")
            result.append(f"{'DOMAIN-SUFFIX' if suffix else 'DOMAIN'},{domain}")
        elif kind == "geoip":
            network = ipaddress.ip_network(value, strict=True)
            result.append(f"{'IP-CIDR' if network.version == 4 else 'IP-CIDR6'},{network}")
        else:
            raise ValueError(f"Unsupported resource kind: {kind}")
    if not result:
        raise ValueError(f"Empty {kind} resource")
    return list(dict.fromkeys(result))


def build(revision):
    template = ROOT / "Ho-New-Config-FakeIP-Template.yaml"
    source = template.read_text()
    config = yaml.safe_load(source)
    other = yaml.safe_load((ROOT / "Ho-New-Config-RedirHost-Template.yaml").read_text())
    if config["rules"] != other["rules"]:
        raise ValueError("Ho-New templates have different routing rules; choose a baseline explicitly")
    resources = sorted({(a[0].lower(), a[1].lower()) for rule in config["rules"]
                        if (a := rule.split(","))[0] in {"GEOSITE", "GEOIP"}})

    def download(resource):
        kind, name = resource
        url = f"{RAW}/{revision}/geo/{kind}/{name}.list"
        with urlopen(url, timeout=60) as response:
            data = response.read()
        entries = convert(kind, data.decode("utf-8-sig"))
        return (f"{kind}/{name}.list", entries,
                {"source": url, "sha256": hashlib.sha256(data).hexdigest(), "rules": len(entries)})

    # Finish every download and validation before replacing any generated files.
    with ThreadPoolExecutor(max_workers=8) as pool:
        downloaded = list(pool.map(download, resources))
    files = {}
    manifest = {"upstream": UPSTREAM, "revision": revision, "resources": {}}
    for path, entries, metadata in downloaded:
        files[path] = f"# Generated by shadowrocket/update.py\n# Source: {metadata['source']}\n" + "\n".join(entries) + "\n"
        manifest["resources"][path] = metadata

    for rule in config["rules"]:
        a = rule.split(",")
        if a[0] != "RULE-SET":
            continue
        local = ROOT / "rule_set" / f"{a[1]}.yaml"
        entries = yaml.safe_load(local.read_text())["payload"]
        for entry in entries:
            if entry.split(",")[0] not in {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD"} or entry.count(",") != 1:
                raise ValueError(f"Unsupported custom rule: {entry}")
        files[f"custom/{a[1]}.list"] = f"# Generated by shadowrocket/update.py\n# Source: rule_set/{a[1]}.yaml\n" + "\n".join(entries) + "\n"

    rules = []
    for line in source.split("\nrules:\n", 1)[1].splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            if not stripped.startswith("# - "):
                rules.append(stripped)
            continue
        rule, _, comment = stripped.removeprefix("- ").partition(" #")
        a = rule.split(",")
        if comment:
            rules.append("#" + comment)
        if a[0] in {"GEOSITE", "GEOIP"}:
            path = f"{a[0].lower()}/{a[1].lower()}.list"
            if path not in files:
                raise ValueError(f"Missing converted resource: {path}")
            extra = ",no-resolve" if "no-resolve" in a[3:] else ""
            rules.append(f"RULE-SET,{PUBLISHED}/{path},{a[2]}{extra}")
        elif a[0] == "RULE-SET":
            rules.append(f"RULE-SET,{PUBLISHED}/custom/{a[1]}.list,{a[2]}")
        elif a[0] == "MATCH":
            rules.append(f"FINAL,{a[1]}")
        else:
            raise ValueError(f"Unsupported routing rule: {rule}")

    current = CONFIG.read_text().split("[Rule]\n", 1)[0]
    general = current.split("[General]\n", 1)[1]
    header = """# 配置名称: Shadowrocket-Ho-New
# 基准来源: Ho-New-Config-FakeIP-Template.yaml（规则分类、顺序与默认策略）
# GeoSite/GeoIP: MetaCubeX/meta-rules-dat 的 meta 分支文本导出，转换结果位于 shadowrocket/。
# 自定义规则: 本仓库 rule_set/*.yaml；运行 uv run shadowrocket/update.py 同步。
# 文本导出不保证包含完整 geosite.dat 的关键词和正则；限制详见 shadowrocket/README.md。
# 全局路由使用「配置」；✅默认代理选 PROXY 时跟随主界面节点。
# 配套去广告模块（需在 Shadowrocket「配置 → 模块」单独安装）:
# https://ghfast.top/https://raw.githubusercontent.com/GMOogway/shadowrocket-rules/master/sr_reject_list.module

"""
    generated = header + "[General]\n" + general + "[Rule]\n" + "\n".join(rules).strip() + "\n"
    generated = generated.replace("# ★ 国外域名兜底（与 nameserver-policy 同一张网；必须放在国内直连规则之前）",
                                  "# 国外域名兜底，必须放在国内直连规则之前")
    files["sources.json"] = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    return files, generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", help="Pinned MetaCubeX meta-branch commit SHA")
    args = parser.parse_args()
    revision = args.revision
    if revision is None:
        revision = subprocess.check_output(
            ["git", "ls-remote", UPSTREAM, "refs/heads/meta"], text=True
        ).split()[0]
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Expected a full commit SHA")
    files, config = build(revision)
    for relative, content in files.items():
        target = OUTPUT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        temp = target.with_suffix(target.suffix + ".tmp")
        temp.write_text(content)
        temp.replace(target)
    CONFIG.write_text(config)
    print(f"Generated {len(files) - 1} rule sets from MetaCubeX {revision}; updated {CONFIG.name}")


if __name__ == "__main__":
    main()
